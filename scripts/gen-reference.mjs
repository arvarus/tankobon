// Generates the parts of the reference documentation that TypeDoc can't: the SQLite schema and
// the IPC channel list. Both are derived from the source files (never from hand-written docs) and
// written to docs/reference/, which is git-ignored.
//
// Fails (exit code 1) when the code can't be parsed as expected, or when the IPC channels declared
// in src/main/ipc/*.ts and used in src/preload.ts differ: the preload can't import the main-process
// constants, so the two lists are kept in sync by hand and this is the check that they are.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const root = path.resolve(import.meta.dirname, '..');
const outDir = path.join(root, 'docs', 'reference');
const read = (relative) => readFileSync(path.join(root, relative), 'utf-8');
const errors = [];
const HEADER = '<!-- Generated by scripts/gen-reference.mjs from the source code. Do not edit. -->\n\n';

// ---------------------------------------------------------------------------------------------
// Database schema: runs the SQL found in the migrations of schema.ts (in file order, which is
// version order) against an in-memory database, then reads the resulting schema back, so the page
// shows what SQLite actually creates.
// ---------------------------------------------------------------------------------------------
function generateSchema() {
  const file = 'src/main/db/schema.ts';
  const source = read(file);
  // Only literal SQL: the helpers' templated statements (`${…}`) are not part of the schema.
  const execBlocks = [...source.matchAll(/db\.exec\(`([\s\S]*?)`\)|db\.exec\('(CREATE [^']*)'\)/g)]
    .map((m) => m[1] ?? m[2])
    .filter((sql) => !sql.includes('${'));
  const addedColumns = [
    ...source.matchAll(/addColumnIfMissing\(\s*db\s*,\s*'(\w+)'\s*,\s*'(\w+)'\s*,\s*("[^"]*"|'[^']*')\s*\)/g),
  ].map((m) => ({ table: m[1], column: m[2], definition: m[3].slice(1, -1) }));
  if (execBlocks.length === 0) {
    errors.push(`${file}: no db.exec(\`…\`) block found in the migrations`);
    return;
  }

  const db = new DatabaseSync(':memory:');
  try {
    // A block that fails may be waiting for a column `addColumnIfMissing()` adds (an index on it):
    // it is run again once the columns are there.
    const deferred = [];
    for (const sql of execBlocks) {
      try {
        db.exec(sql);
      } catch {
        deferred.push(sql);
      }
    }
    for (const { table, column, definition } of addedColumns) {
      db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
    }
    for (const sql of deferred) db.exec(sql);
  } catch (error) {
    errors.push(`${file}: the schema SQL doesn't run: ${error.message}`);
    return;
  }

  const tables = db
    .prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
    .all()
    .map((row) => row.name);

  let md = `${HEADER}# Database schema\n\n`;
  md += `The SQLite schema built by the versioned migrations of \`${file}\` (see \`MIGRATIONS\`). Columns marked *added later* are added to existing databases by \`addColumnIfMissing()\` (see the [architecture](../architecture.md#local-database-src-main-db)).\n`;
  for (const table of tables) {
    const columns = db.prepare(`PRAGMA table_info(${table})`).all();
    const unique = new Set(
      db
        .prepare(`PRAGMA index_list(${table})`)
        .all()
        .filter((index) => index.unique && index.origin === 'u')
        .flatMap((index) => db.prepare(`PRAGMA index_info(${index.name})`).all().map((info) => info.name)),
    );
    md += `\n## \`${table}\`\n\n| Column | Type | Constraints | Default | Added later |\n|---|---|---|---|---|\n`;
    for (const column of columns) {
      const constraints = [
        column.pk ? 'PRIMARY KEY' : '',
        column.notnull ? 'NOT NULL' : '',
        unique.has(column.name) ? 'UNIQUE' : '',
      ].filter(Boolean);
      const later = addedColumns.some((added) => added.table === table && added.column === column.name);
      md += `| \`${column.name}\` | ${column.type} | ${constraints.join(', ')} | ${column.dflt_value === null ? '' : `\`${column.dflt_value}\``} | ${later ? 'yes' : ''} |\n`;
    }
  }
  const indexes = db
    .prepare("SELECT name, tbl_name FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL ORDER BY name")
    .all();
  if (indexes.length > 0) {
    md += `\n## Indexes\n\n| Index | Table | Columns |\n|---|---|---|\n`;
    for (const index of indexes) {
      const columns = db.prepare(`PRAGMA index_info(${index.name})`).all().map((info) => info.name);
      md += `| \`${index.name}\` | \`${index.tbl_name}\` | ${columns.map((c) => `\`${c}\``).join(', ')} |\n`;
    }
  }
  db.close();
  writeFileSync(path.join(outDir, 'schema.md'), md);
}

// ---------------------------------------------------------------------------------------------
// IPC channels: the `*_CHANNELS` constants of src/main/ipc/*.ts on one side, the channels the
// preload's `api` object invokes or listens to on the other.
// ---------------------------------------------------------------------------------------------
function mainChannels() {
  const channels = new Map();
  const ipcDir = 'src/main/ipc';
  for (const name of readdirSync(path.join(root, ipcDir)).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'))) {
    const file = `${ipcDir}/${name}`;
    const source = read(file);
    for (const [, constName, body] of source.matchAll(/export const (\w+_CHANNELS) = \{([\s\S]*?)\} as const/g)) {
      for (const [, key, channel] of body.matchAll(/(\w+): '([^']+)'/g)) {
        const ref = `${constName}.${key}`;
        const handled = new RegExp(`\\bhandle\\(\\s*${constName}\\.${key}\\b`).test(source);
        const pushed = new RegExp(`\\.send\\(\\s*${constName}\\.${key}\\b`).test(source);
        if (!handled && !pushed) errors.push(`${file}: ${ref} ('${channel}') is declared but never handled nor sent`);
        channels.set(channel, { file, ref, direction: pushed ? 'main → renderer (push)' : 'renderer → main (invoke)' });
      }
    }
  }
  return channels;
}

// The descriptions come from the TSDoc of the interfaces typing `api` (`TankobonApi` and the
// per-namespace interfaces its members point to), the same comments TypeDoc renders.
function preloadDocs(source, file) {
  const interfaces = new Map();
  for (const [, name, body] of source.matchAll(/^export interface (\w+)(?:<[^>]*>)? \{\n([\s\S]*?)^\}/gm)) {
    const members = new Map();
    let pendingDoc = [];
    for (const line of body.split('\n')) {
      const docLine = line.match(/^\s*\/\*\*\s?(.*?)\s*(\*\/)?$/) ?? (pendingDoc.length && line.match(/^\s*\*\s?(.*?)\s*(\*\/)?$/));
      if (docLine) {
        if (docLine[1] && docLine[1] !== '/') pendingDoc.push(docLine[1]);
        continue;
      }
      const member = line.match(/^ {2}(\w+)[<(:]/);
      if (member) {
        members.set(member[1], { doc: pendingDoc.join(' ').trim(), type: line.match(/^ {2}\w+: (\w+);$/)?.[1] });
        pendingDoc = [];
      }
    }
    interfaces.set(name, members);
  }
  const root = interfaces.get('TankobonApi');
  if (!root) {
    errors.push(`${file}: interface TankobonApi not found`);
    return new Map();
  }
  // namespace → (method → doc)
  return new Map([...root].map(([namespace, { type }]) => [namespace, interfaces.get(type) ?? new Map()]));
}

function preloadChannels() {
  const file = 'src/preload.ts';
  const source = read(file);
  const docs = preloadDocs(source, file);
  const apiStart = source.indexOf('const api: TankobonApi = {');
  if (apiStart === -1) errors.push(`${file}: \`const api: TankobonApi = {\` not found`);
  const lines = source.slice(Math.max(apiStart, 0)).split('\n');
  const channels = new Map();
  let namespace = null;
  let method = null;
  for (const line of lines) {
    const ns = line.match(/^ {2}(\w+): \{$/);
    const fn = line.match(/^ {4}(\w+)(?:: |\()/);
    if (ns) {
      namespace = ns[1];
      continue;
    }
    if (fn && namespace) method = fn[1];
    const call = line.match(/ipcRenderer\.(invoke|on)\('([^']+)'/);
    if (call && namespace && method) {
      const doc = docs.get(namespace)?.get(method)?.doc ?? '';
      channels.set(call[2], { method: `window.tankobon.${namespace}.${method}`, doc });
    }
  }
  if (channels.size === 0) errors.push(`${file}: no ipcRenderer.invoke/on call found`);
  return channels;
}

function generateIpc() {
  const main = mainChannels();
  const preload = preloadChannels();
  for (const channel of main.keys()) {
    if (!preload.has(channel)) errors.push(`IPC channel '${channel}' is declared in ${main.get(channel).file} but not used in src/preload.ts`);
  }
  for (const [channel, { method, doc }] of preload) {
    if (!doc) errors.push(`src/preload.ts: ${method} ('${channel}') has no /** … */ comment on its interface member`);
    if (!main.has(channel)) errors.push(`IPC channel '${channel}' is used in src/preload.ts but not declared in any src/main/ipc/*.ts *_CHANNELS constant`);
  }

  let md = `${HEADER}# IPC channels\n\n`;
  md += 'Every channel between the renderer and the main process, from the `*_CHANNELS` constants in `src/main/ipc/` and the `window.tankobon` API in `src/preload.ts` (whose type is [`TankobonApi`](./api/preload/interfaces/TankobonApi.md)).\n\n';
  md += '| Channel | Direction | Preload API | Handler | Description |\n|---|---|---|---|---|\n';
  for (const channel of [...main.keys()].sort()) {
    const { file, ref, direction } = main.get(channel);
    const api = preload.get(channel);
    md += `| \`${channel}\` | ${direction} | ${api ? `\`${api.method}\`` : ''} | \`${ref}\` in \`${file}\` | ${api?.doc ?? ''} |\n`;
  }
  writeFileSync(path.join(outDir, 'ipc.md'), md);
}

mkdirSync(outDir, { recursive: true });
generateSchema();
generateIpc();

if (errors.length > 0) {
  console.error(`gen-reference: ${errors.length} problem(s):\n${errors.map((e) => `  - ${e}`).join('\n')}`);
  process.exit(1);
}
console.log('gen-reference: docs/reference/schema.md and docs/reference/ipc.md generated');
